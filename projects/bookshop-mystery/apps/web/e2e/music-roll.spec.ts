import { expect, test } from '@playwright/test';

test('작은 화면에서 양 끝을 대조하고 선택을 보존하며 오르골 사건을 해결한다', async ({ page }) => {
  const query = '?from=youtube-shorts&item=one&item=two#roll';
  const path = '/cases/music-roll/' + query;
  await page.setViewportSize({ width: 320, height: 568 });
  await page.goto(path);
  await expect(page).toHaveTitle('마지막으로 울린 오르골');
  const start = page.getByRole('button', { name: '조사 시작', exact: true });
  await expect(start).toBeInViewport({ ratio: 1 });
  await start.click();

  const timeline = page.getByRole('list', { name: '조사 진행도' });
  const actions = page.locator('.case-action');
  await expect(page.getByRole('heading', { name: '마감 종소리의 녹음' })).toBeVisible();
  const recording = page.getByLabel('전시실 마감 종소리 녹음');
  await expect(recording).toHaveAttribute('preload', 'none');
  await expect(recording).toBeInViewport({ ratio: 1 });
  await expect(recording).toHaveJSProperty('paused', true);
  await recording.focus();
  await page.keyboard.press('Space');
  await expect(recording).toHaveJSProperty('paused', false);
  await expect(timeline.getByRole('button', { name: '추리 잠김' })).toBeDisabled();
  await timeline.getByRole('button', { name: '종이띠', exact: true }).click();
  const figure = page.getByRole('figure', { name: '띠별로 종이 울리는 시각' });
  const paperB = figure.getByRole('listitem').filter({ hasText: 'B 띠' });
  await expect(paperB).toContainText('0초, 2초, 5초, 6초');
  const right = page.getByRole('button', { name: '오른쪽 끝부터' });
  await expect(right).toBeInViewport({ ratio: 1 });
  await right.click();
  await expect(right).toHaveAttribute('aria-pressed', 'true');
  await expect(paperB).toContainText('0초, 1초, 4초, 6초');
  const left = page.getByRole('button', { name: '왼쪽 끝부터' });
  await left.click();
  await expect(paperB).toContainText('0초, 2초, 5초, 6초');
  await expect(page.getByText('녹음 속 종소리')).toBeInViewport({ ratio: 1 });
  await expect(actions.getByRole('button', { name: '구동기 보기' })).toBeInViewport({ ratio: 1 });
  await page.goBack();
  await expect(page.getByRole('heading', { name: '마감 종소리의 녹음' })).toBeVisible();
  await actions.getByRole('button', { name: '구동기 보기' }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: '오르골 구동기' })).toBeVisible();
  await timeline.getByRole('button', { name: '추리', exact: true }).click();

  const roll = page.getByRole('combobox', { name: '사용한 종이띠' });
  const direction = page.getByRole('combobox', { name: '먼저 넣은 쪽' });
  const submit = actions.getByRole('button', { name: '추리 제출' });
  await roll.selectOption('A');
  await direction.selectOption('left');
  await submit.click();
  await expect(page.getByRole('status')).toContainText('3번째 종이 3초');
  await timeline.getByRole('button', { name: '녹음 확인 완료' }).click();
  await timeline.getByRole('button', { name: '추리', exact: true }).click();
  await expect(roll).toHaveValue('A');
  await roll.selectOption('B');
  await direction.selectOption('right');
  await submit.click();
  await expect(page.getByRole('heading', { name: '마지막 종소리를 되찾았어요' })).toBeVisible();
  await expect(page).toHaveURL((url) => url.pathname + url.search + url.hash === path);
  await actions.getByRole('link', { name: '사건 목록' }).click();
  await page.getByRole('link', { name: '마지막으로 울린 오르골' }).click();
  await expect(page.getByRole('button', { name: '결말 다시 보기' })).toBeVisible();
});
