import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { imageSize } from 'image-size';
import { format, resolveConfig } from 'prettier';

import { readContent } from './content';

const root = fileURLToPath(new URL('..', import.meta.url));
const { articles, imports, redirects } = await readContent(root);
const lib = path.join(root, 'src/entities/article/lib');
const dimensions: Record<string, { width: number; height: number }> = {};
const imagesDir = path.join(root, 'public/images');
for (const file of (await readdir(imagesDir, { recursive: true })).sort()) {
  if (!/\.(png|jpe?g|webp|gif|avif|svg)$/i.test(file)) continue;
  const size = imageSize(await readFile(path.join(imagesDir, file)));
  dimensions[`/images/${file.split(path.sep).join('/')}`] = { width: size.width, height: size.height };
}

const registry = `// Generated by scripts/generate-article-registry.ts. Do not edit.\nimport type {Locale} from '../model/types';\nconst loaders = {\n${imports.map(({ id, locale }) => `  ${JSON.stringify(`${id}/${locale}`)}: () => import(${JSON.stringify(`../../../../content/posts/${id}/${locale}.mdx`)}),`).join('\n')}\n};\nexport async function loadArticle(id: string, locale: Locale) {\n  const key = \`\${id}/\${locale}\`;\n  const loader = loaders[key as keyof typeof loaders];\n  if (!loader) throw new Error(\`No content: \${key}\`);\n  return loader();\n}\n`;
const unformatted = new Map([
  [path.join(root, 'src/shared/config/image-sizes.json'), JSON.stringify(dimensions, null, 2) + '\n'],
  [path.join(lib, 'index.json'), JSON.stringify(articles, null, 2) + '\n'],
  [path.join(lib, 'registry.ts'), registry],
  [path.join(root, 'content/generated-redirects.json'), JSON.stringify(redirects, null, 2) + '\n'],
]);
const files = new Map(
  await Promise.all(
    [...unformatted].map(
      async ([file, source]) =>
        [
          file,
          await format(source, {
            ...(await resolveConfig(file)),
            filepath: file,
          }),
        ] as const,
    ),
  ),
);
if (process.argv.includes('--check')) {
  for (const [file, expected] of files) {
    let actual = '';
    try {
      actual = await readFile(file, 'utf8');
    } catch {
      /* Missing generated file is stale. */
    }
    if (actual !== expected)
      throw new Error(`Stale generated content: ${path.relative(root, file)}. Run yarn content:generate.`);
  }
} else {
  await mkdir(lib, { recursive: true });
  for (const [file, source] of files) {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, source);
  }
}
console.log(
  `Validated ${articles.length} article locales, ${imports.length} static MDX imports, ${redirects.length} redirects.`,
);
